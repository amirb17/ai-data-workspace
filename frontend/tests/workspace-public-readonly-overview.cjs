const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = rel => fs.readFileSync(path.join(__dirname, '..', rel), 'utf8')
const hook = read('src/features/workspaces/useWorkspacePreparation.ts')
const view = read('src/features/workspaces/components/WorkspacePreparation.tsx')
assert.match(hook, /error instanceof ApiError/)
assert.match(hook, /error\.status !== 403/)
assert.match(hook, /analytics = null/)
assert.match(view, /analytics\?\.summary\?\.confirmed_relationships/)
assert.match(view, /analytics\?\.metrics_fresh \?\? "Unavailable"/)
console.log('Workspace Overview treats release-blocked analytics as unavailable, not as zero.')
