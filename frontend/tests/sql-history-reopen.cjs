// SQL history must restore query text and historical metadata without submitting
// the query. A deliberate Run Query remains the only SQL execution action.
const fs=require('node:fs')
const assert=require('node:assert/strict')
const page=fs.readFileSync('src/features/workspaces/sql/SqlPage.tsx','utf8')
const history=fs.readFileSync('src/features/workspaces/sql/SqlSavedQueries.tsx','utf8')
const api=fs.readFileSync('src/services/api/sqlAnalytics.ts','utf8')
assert.match(page,/openHistory=\{e=>guard\(\(\)=>\{/)
const open=page.match(/openHistory=\{e=>guard\(\(\)=>\{(.+?)\}\)\}/)
assert.ok(open,'History callback must use the existing unsaved-draft guard')
assert.match(open[1],/setText\(e\.sql_text\|\|''\)/)
assert.match(open[1],/setBaseline\(e\.sql_text\|\|''\)/)
assert.match(open[1],/setMode\('sql'\)/)
assert.match(open[1],/data\.setResult\(\{\.\.\.e,rows:\[\],historical:true\}\)/)
assert.doesNotMatch(open[1],/executeSql|run\(/)
assert.match(page,/function run\(\)/)
assert.match(page,/await executeSql\(/)
assert.match(history,/Open SQL — no execution/)
assert.match(history,/disabled=\{!e\.sql_text\}/)
assert.match(history,/named\.get\(e\.saved_query_id\)/)
assert.match(history,/e\.sources\.map/)
assert.match(history,/status==='ALL'/)
assert.match(history,/History stores|Opening history restores SQL/)
assert.match(api,/saved_query_id\?:number\|null/)
console.log('SQL query history reopen regression guards passed')
