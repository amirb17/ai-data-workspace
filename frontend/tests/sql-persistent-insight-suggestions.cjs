// Static regression checks keep suggestions present after execution and grounded in catalog data.
const fs=require('node:fs')
const assert=require('node:assert/strict')
const page=fs.readFileSync('src/features/workspaces/sql/SqlPage.tsx','utf8')
const suggestion=fs.readFileSync('src/features/workspaces/sql/sqlInsightSuggestions.ts','utf8')
const component=fs.readFileSync('src/features/workspaces/sql/SqlSuggestions.tsx','utf8')
assert.match(page,/!!available\.length&&<SqlSuggestions/)
assert.doesNotMatch(page,/!!available\.length&&!activeSql\.trim\(\)/)
assert.match(page,/<SqlResults/)
assert.match(component,/onOpen\(idea\.sql\)/)
assert.match(component,/aria-pressed=\{filter===category\}/)
assert.match(component,/disabled=\{busy\}/)
assert.match(suggestion,/dataset\.columns\.find\(c=>c\.queryable/)
assert.match(suggestion,/catalog\.relationships/)
assert.match(suggestion,/relation\.child\.columns\.length!==1/)
assert.match(suggestion,/\['ONE_TO_MANY','ONE_TO_ONE'\]/)
assert.match(suggestion,/quoteIdentifier/)
assert.match(suggestion,/customer_segment/)
assert.match(suggestion,/revenue_inr/)
console.log('SQL persistent insight suggestion guards passed')
